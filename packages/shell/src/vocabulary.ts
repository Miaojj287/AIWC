export const REDIRECT_RE = /(?:^|\s)(?:\d?>>?|&>|>\|)\s*(\S+)/g
/**
 * The same redirection glued to the word in front of it — `echo hi>out.txt` writes exactly what
 * `echo hi > out.txt` writes. Matched over the quote-blanked line so text the shell never reads as
 * syntax (`echo "<html>"`) does not count; `-`, `=` and `!` in front of it are comparisons.
 */
export const GLUED_REDIRECT_RE = /(?<![<>&|\-=!\s])(?:\d?>>?|&>|>\|)\s*(\S+)/g
export const HEREDOC_RE = /<<-?\s*['"]?\w+/

